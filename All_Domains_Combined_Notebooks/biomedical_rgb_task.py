#Evaluation Function
# NEW: summary computation split out so it can also run over saved CSVs later.
def summarize(df,model_name,dataset_name,noise_ratio):
    valid=df[df["APIError"].isna()]
    n=len(valid)

    def rate(col):
        if n==0:
            return None,None
        p=valid[col].mean()
        return round(p*100,2),round(math.sqrt(p*(1-p)/n)*100,2)   # NEW: standard error

    acc,acc_se=rate("Correct")
    rej,rej_se=rate("Rejected")
    ed,ed_se=rate("ErrorDetected")

    detected=valid[valid["ErrorDetected"]] if n else valid
    cr=round(detected["Correct"].mean()*100,2) if len(detected) else None

    return {
        "Model":model_name,
        "Dataset":dataset_name,
        "NoiseRatio":noise_ratio,
        "n":n,
        "Errors":len(df)-n,
        "Accuracy":acc,
        "Accuracy_SE":acc_se,
        "RejectionRate":rej,
        "RejectionRate_SE":rej_se,
        "RejectionRate_Lenient":round(valid["RejectedLenient"].mean()*100,2) if n else None,
        "ErrorDetection":ed,
        "ErrorDetection_SE":ed_se,
        "ErrorCorrection":cr,
        "ErrorCorrection_n":len(detected),
        "MeanDocs":round(valid["NumDocs"].mean(),2) if n else None
    }


# CHANGED: takes a noise ratio, checkpoints per row to Drive, keeps API errors separate,
# and records rejection / error-detection alongside accuracy.
def evaluate_dataset(
        dataset,
        model_name,
        dataset_name,
        noise_ratio
):
    filename=os.path.join(
        BASE_OUT,
        f"{model_name}_{dataset_name}_{noise_ratio}.csv"    # CHANGED: was /content
    )

    # resume from an existing checkpoint
    results=[]
    done=set()
    if os.path.exists(filename):
        prev=pd.read_csv(filename)
        results=prev.to_dict("records")
        done=set(prev[prev["APIError"].isna()]["id"].astype(int))
        print(f"  resuming {os.path.basename(filename)}: {len(done)} already done")

    consecutive_errors=0

    for example in tqdm(dataset,desc=f"{model_name} {dataset_name} r={noise_ratio}"):
        if example["id"] in done:
            continue

        question=example["query"]
        answers=example["answer"]

        # seed derived from the row id, so a resumed row gets the same documents
        rng=random.Random(f"{SEED}|{dataset_name}|{noise_ratio}|{example['id']}")
        documents,padded=create_documents(
                    example,
                    dataset_name,
                    noise_ratio,
                    rng
                )
        prompt=generate_prompt(
                    question,
                    documents
                )
        response,error=get_response(
                    model_name,
                    prompt
                )

        # NEW: bail out early instead of burning 50 minutes on a dead endpoint
        consecutive_errors = consecutive_errors+1 if error else 0
        if consecutive_errors>=5:
            print(f"\n  5 consecutive failures on {model_name} - stopping this cell.")
            print(f"  last error: {str(error)[:200]}")
            break

        hit,total_groups=groups_hit(response,answers)

        results.append(
            {
            "id":example["id"],
            "Question":question,
            "Expected":str(answers),
            "Response":response,
            "Correct":is_correct(response,answers),
            "GroupsHit":hit,
            "GroupsTotal":total_groups,
            "Rejected":rejected(response),
            "RejectedLenient":rejected(response,lenient=True),
            "ErrorDetected":error_detected(response),
            "ErrorDetectedLenient":error_detected(response,lenient=True),
            "NumDocs":len(documents),
            "Padded":padded,
            "Model":model_name,
            "Dataset":dataset_name,
            "NoiseRatio":noise_ratio,
            "APIError":error
            }
        )

        pd.DataFrame(results).to_csv(filename,index=False)   # CHANGED: was once at the end
        time.sleep(SLEEP_SECONDS)

    summary=summarize(pd.DataFrame(results),model_name,dataset_name,noise_ratio)

    print()
    print(model_name,"|",dataset_name,"| ratio",noise_ratio)
    print(f"  n={summary['n']}  (errors: {summary['Errors']})")
    if dataset_name=="Rejection":
        print(f"  rejection {summary['RejectionRate']} +/- {summary['RejectionRate_SE']} %"
              f"   (lenient {summary['RejectionRate_Lenient']} %)")
    elif dataset_name=="Counterfactual" and noise_ratio=="doc":
        print(f"  accuracy {summary['Accuracy']} +/- {summary['Accuracy_SE']} %"
              f" | ED {summary['ErrorDetection']} % | CR {summary['ErrorCorrection']} %"
              f" (n={summary['ErrorCorrection_n']})")
    else:
        print(f"  accuracy {summary['Accuracy']} +/- {summary['Accuracy_SE']} %")

    return summary

