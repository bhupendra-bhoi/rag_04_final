#preparing docs
# CHANGED: takes a noise ratio and caps at 5 documents (the paper's setting).
# noise ratio r -> n_negative = round(5r), n_positive = 5 - n_negative
N_DOCS = 5

def create_documents(example,task,noise_ratio,rng):

    # Counterfactual: corrupted documents ONLY.
    # CHANGED: no longer adds example["positive"] as well.
    if task=="Counterfactual":
        if noise_ratio=="closed":
            return [],0                       # closed book -> gives ACC baseline
        documents=list(example["positive_wrong"])
        rng.shuffle(documents)
        return documents,0

    n_neg=int(round(N_DOCS*noise_ratio))
    n_pos=N_DOCS-n_neg

    # Integration: positive is a LIST OF GROUPS, one per sub-question.
    # Deal round-robin so every sub-question keeps at least one document.
    if task=="Integration":
        pools=[list(g) for g in example["positive"]]
        for p in pools:
            rng.shuffle(p)
        positive,i=[],0
        while len(positive)<n_pos and any(pools):
            pool=pools[i%len(pools)]
            if pool:
                positive.append(pool.pop())
            i+=1
    else:
        positive=rng.sample(
            example["positive"],
            min(n_pos,len(example["positive"]))
        )

    padded=n_pos-len(positive)                # short rows get topped up from negatives
    negative=rng.sample(
        example["negative"],
        min(n_neg+padded,len(example["negative"]))
    )

    documents=positive+negative
    rng.shuffle(documents)
    return documents,padded

