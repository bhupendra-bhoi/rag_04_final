#other helper methods

# CHANGED: strips punctuation and collapses whitespace.
# 'Jan. 2, 2022' and 'January 2, 2022' now reduce to the same tokens.
_PUNCT = re.compile(r"[^\w\s]")
_WS    = re.compile(r"\s+")

def normalize(text):
    if text is None:
        return ""
    return _WS.sub(" ", _PUNCT.sub(" ", str(text).lower())).strip()


# CHANGED: replaces flatten_answers. Keeps the group structure instead of destroying it.
#   "Tampa, Florida"                    -> [["Tampa, Florida"]]
#   ["medical"]                         -> [["medical"]]
#   [["Jan 2, 2022","January 2 2022"]]  -> [["Jan 2, 2022","January 2 2022"]]
#   ["Bertozzi","Meldal","Sharpless"]   -> [["Bertozzi"],["Meldal"],["Sharpless"]]
def as_groups(answers):
    if isinstance(answers,str):
        return [[answers]]
    return [
        [g] if isinstance(g,str) else list(g)
        for g in answers
    ]


# NEW: word-boundary match, so "12" does not match inside "2012"
def contains(haystack,needle):
    n = normalize(needle)
    if not n:
        return False
    return re.search(
        r"(?<!\w)" + re.escape(n) + r"(?!\w)",
        haystack
    ) is not None


# CHANGED: ALL groups must match (was: ANY single alias)
def is_correct(response,answers):
    if not response:
        return False
    response = normalize(response)
    return all(
        any(contains(response,a) for a in group)
        for group in as_groups(answers)
    )


# NEW: how many groups were hit, for partial-credit error analysis
def groups_hit(response,answers):
    if not response:
        return 0,len(as_groups(answers))
    response = normalize(response)
    groups = as_groups(answers)
    hit = sum(
        1 for group in groups
        if any(contains(response,a) for a in group)
    )
    return hit,len(groups)


# CHANGED: matches the Figure 3 trigger sentence, not "I don't know."
# The lenient variant catches models that refused in their own words - report both,
# the gap is a finding (the paper's own Rej vs Rej* gap is 24.67 vs 45.00).
REJECT_PHRASE  = "I can not answer the question because of the insufficient information in documents"
FACTERR_PHRASE = "There are factual errors in the provided documents"

_REJECT_LENIENT = [
    "can not answer","cannot answer","can t answer",
    "insufficient information","insufficient info",
    "have enough information","enough information to answer",
    "do not contain","does not contain","no information",
    "unable to answer","not provided in the documents",
]
_FACTERR_LENIENT = [
    "factual error","factually incorrect","factually inaccurate",
    "incorrect information","inconsistenc","contradict",
    "is wrong","are wrong","error in the provided",
]

def rejected(response,lenient=False):
    if not response:
        return False
    r = normalize(response)
    if normalize(REJECT_PHRASE) in r:
        return True
    return lenient and any(p in r for p in _REJECT_LENIENT)


# NEW: error detection, required for Counterfactual Robustness
def error_detected(response,lenient=False):
    if not response:
        return False
    r = normalize(response)
    if normalize(FACTERR_PHRASE) in r:
        return True
    return lenient and any(p in r for p in _FACTERR_LENIENT)

