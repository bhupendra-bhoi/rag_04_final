def generate_prompt(question,documents):
    # NEW: empty documents = closed-book pass, used for the counterfactual ACC baseline
    if not documents:
        return f"""{RGB_INSTRUCTION}

Question:
{question}
"""

    context="\n\n".join(
        f"Document {i}: {d}" for i,d in enumerate(documents)
    )
    prompt=f"""{RGB_INSTRUCTION}

Document:
{context}

Question:
{question}
"""
    return prompt

