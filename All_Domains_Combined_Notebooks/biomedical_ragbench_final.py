def clean_answer(text):
    """Strip any leaked reasoning scaffold (belt-and-suspenders for the biomedical two-step)."""
    t = text.strip()
    for marker in ["STEP 2 - Answer:", "STEP 2:", "STEP 2", "Answer:"]:
        if marker in t:
            t = t.split(marker)[-1].strip()
    t = re.sub(r"^\s*STEP\s*1\b.*?(?:\n\s*\n|$)", "", t, flags=re.DOTALL | re.IGNORECASE).strip()
    return t if t else text.strip()

