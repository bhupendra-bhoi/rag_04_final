def rrf_fuse(dense_ids, sparse_ids, k=60):
    """Reciprocal Rank Fusion: merge two ranked lists by summing 1/(k+rank).
    Rewards docs ranked highly by EITHER retriever; k=60 is the standard damping constant."""
    scores = {}
    for r, i in enumerate(dense_ids):
        scores[i] = scores.get(i, 0.0) + 1.0 / (k + r + 1)
    for r, i in enumerate(sparse_ids):
        scores[i] = scores.get(i, 0.0) + 1.0 / (k + r + 1)
    return [i for i, _ in sorted(scores.items(), key=lambda x: -x[1])]

def retrieve(question, top_k=TOP_K):
    # Widen the candidate pool when hybrid/rerank will prune it back down to top_k
    wide = max(RETRIEVE_WIDE, top_k) if (USE_HYBRID or USE_RERANKER) else top_k
    wide = min(wide, len(chunks))

    # --- Stage 1: dense retrieval (always) ---
    q_emb = embedder.encode([question], convert_to_numpy=True, normalize_embeddings=True)
    _, didx = index.search(q_emb, wide)
    dense_ids = [int(i) for i in didx[0]]

    # --- Stage 2: sparse + RRF fusion (only if hybrid) ---
    if USE_HYBRID:
        s = bm25.get_scores(_tok(question))
        sparse_ids = [int(i) for i in np.argsort(s)[::-1][:wide]]
        cand = rrf_fuse(dense_ids, sparse_ids)[:wide]
    else:
        cand = dense_ids

    # --- Stage 3: cross-encoder rerank (only if rerank) ---
    if USE_RERANKER and cand:
        rs = reranker.predict([(question, chunks[i]) for i in cand], show_progress_bar=False)
        order = np.argsort(rs)[::-1][:top_k]
        final = [cand[int(o)] for o in order]
    else:
        final = cand[:top_k]

    return [{"doc_id": i, "parent_id": chunk_parent[i], "text": chunks[i]} for i in final]

