def _cont_adherence(jstr):
    if pd.isna(jstr):
        return np.nan
    jo = json.loads(jstr)
    info = jo.get("sentence_support_information", [])
    if info:
        return sum(1 for s in info if s.get("fully_supported", False)) / len(info)
    return 1.0 if jo.get("overall_supported", False) else 0.0

def rmse_masked(dfr, predcol, goldcol):
    p = pd.to_numeric(dfr[predcol], errors="coerce")
    g = pd.to_numeric(dfr[goldcol], errors="coerce")
    m = p.notna() & g.notna()
    if not m.any():
        return float("nan"), 0
    return float(np.sqrt(np.mean((p[m] - g[m]) ** 2))), int(m.sum())

