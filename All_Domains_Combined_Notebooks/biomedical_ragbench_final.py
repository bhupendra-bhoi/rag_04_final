# Abbreviations that end in "." but don't end a sentence — protects the regex fallback
# from splitting "e.g." or "et al." mid-sentence. (nltk handles these natively.)
ABBR = {"eg","ie","vs","fig","no","cf","al","approx","dr","etc","eq","ref","spp","sp","st","mr","ms"}

def split_sentences(text):
    text = text.replace("\n", " ").strip()
    if not text:
        return []
    if _HAVE_NLTK:
        try:
            return [s.strip() for s in sent_tokenize(text) if s.strip()]
        except Exception:
            pass
    # regex fallback with light abbreviation protection
    parts = re.split(r"(?<=[.!?])\s+", text)
    out, buf = [], ""
    for p in parts:
        buf = (buf + " " + p).strip() if buf else p
        toks = buf.split()
        last = re.sub(r"[^A-Za-z]", "", toks[-1]).lower() if toks else ""
        if last in ABBR:      # sentence "ended" on an abbreviation -> keep accumulating
            continue
        out.append(buf); buf = ""
    if buf:
        out.append(buf)
    return [s.strip() for s in out if s.strip()]

def make_chunks(doc, mode="window", window=3, stride=2):
    if mode == "whole":
        return [doc]                          # R0: one chunk = one whole document
    title, _, passage = doc.partition("\nPassage:")
    title = title.replace("Title:", "").strip()
    sents = split_sentences(passage)
    if not sents:
        return [doc]                          # nothing to split -> fall back to whole doc
    if mode == "sentence":
        groups = [[s] for s in sents]         # one sentence per chunk (finest)
    else:  # "window"
        groups, i = [], 0
        while i < len(sents):
            groups.append(sents[i:i + window])
            if i + window >= len(sents):
                break
            i += stride                       # advance by stride -> overlap = window - stride
    # Re-attach the title to every chunk so retrieval keeps the paper context
    return [f"Title: {title} | " + " ".join(g) for g in groups]

