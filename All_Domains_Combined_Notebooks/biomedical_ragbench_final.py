def is_rate_limit_error(error):
    t = str(error).lower()
    return any(p in t for p in ["rate limit", "rate_limit", "rate_limit_exceeded", "tokens per day", "tpd", "429"])

def is_daily_limit(error):
    t = str(error).lower()
    return any(p in t for p in ["per day", "tpd", "tokens per day"])

def groq_with_backoff(fn, *args, max_retries=5, **kwargs):
    """Retry on per-MINUTE limits; re-raise per-DAY limits so the loop stops & checkpoints."""
    for attempt in range(max_retries):
        try:
            return fn(*args, **kwargs)
        except Exception as e:
            if is_rate_limit_error(e) and not is_daily_limit(e):
                wait = min(60, 2 ** attempt + 1)
                print(f"  per-minute limit, sleeping {wait}s (attempt {attempt+1})")
                time.sleep(wait); continue
            raise
    raise RuntimeError("max retries exceeded on Groq call")

