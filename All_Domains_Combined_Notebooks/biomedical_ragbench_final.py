def _gold_parents(row):
    local_rel = set()
    for key in row["all_relevant_sentence_keys"]:
        m = re.match(r"(\d+)", str(key))
        if m:
            local_rel.add(int(m.group(1)))
    if not local_rel:
        return None
    ex = list(row["documents"])
    gold = {doc_to_gid.get(ex[li]) for li in local_rel if li < len(ex)}
    gold.discard(None)
    return gold or None

def run_recall_grid():
    out = []
    maxk = max(TOPK_CANDIDATES)
    for emb_name in EMBED_CANDIDATES:
        emb = SentenceTransformer(emb_name)
        for window in WINDOW_CANDIDATES:
            lc, lp = [], []
            for di, doc in enumerate(unique_docs):
                for ch in make_chunks(doc, "window", window, CHUNK_STRIDE):
                    lc.append(ch); lp.append(di)
            vecs = emb.encode(lc, convert_to_numpy=True, normalize_embeddings=True,
                              batch_size=64, show_progress_bar=False)
            idx = faiss.IndexFlatIP(vecs.shape[1]); idx.add(vecs)
            lbm = BM25Okapi([_tok(c) for c in lc]) if SWEEP_HYBRID else None

            per_k = {k: [] for k in TOPK_CANDIDATES}
            for i in range(min(SWEEP_N, len(test_data))):
                row = test_data[i]
                gold = _gold_parents(row)
                if not gold:
                    continue
                q = row["question"]
                wide = max(RETRIEVE_WIDE, maxk) if (SWEEP_HYBRID or SWEEP_RERANK) else maxk
                wide = min(wide, len(lc))
                qe = emb.encode([q], convert_to_numpy=True, normalize_embeddings=True)
                _, di_ = idx.search(qe, wide); dense = [int(x) for x in di_[0]]
                if SWEEP_HYBRID:
                    s = lbm.get_scores(_tok(q)); sp = [int(x) for x in np.argsort(s)[::-1][:wide]]
                    cand = rrf_fuse(dense, sp)[:wide]
